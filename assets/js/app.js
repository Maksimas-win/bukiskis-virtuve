const projectFigures = { total: 6200, raised: 1500 };
projectFigures.remaining = projectFigures.total - projectFigures.raised;
projectFigures.progress = (projectFigures.raised / projectFigures.total) * 100;

const STORAGE_KEY = 'bukiskis-virtuve-language';
const yearNode = document.querySelector('#year');
const langButtons = document.querySelectorAll('.lang-btn');
const translatableNodes = document.querySelectorAll('[data-i18n]');
const translatableAltNodes = document.querySelectorAll('[data-i18n-alt]');
const translatableAriaNodes = document.querySelectorAll('[data-i18n-aria]');
const figureNodes = document.querySelectorAll('[data-figure]');
const progressFill = document.querySelector('.progress-fill');
const contactLink = document.querySelector('[data-contact-link]');

const storage = {
  get() { try { return localStorage.getItem(STORAGE_KEY); } catch { return null; } },
  set(value) { try { localStorage.setItem(STORAGE_KEY, value); } catch {} }
};

const getLocale = lang => lang === 'ru' ? 'ru-RU' : 'lt-LT';
const formatCurrency = (value, lang) => new Intl.NumberFormat(getLocale(lang)).format(value) + ' €';
const formatPercent = (value, lang) => new Intl.NumberFormat(getLocale(lang), { minimumFractionDigits: 1, maximumFractionDigits: 1 }).format(value) + ' %';

function updateMeta(lang) {
  document.title = translations[lang].pageTitle;
  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.setAttribute('content', translations[lang].pageDescription);
}

function setLanguage(lang) {
  const selected = translations[lang] ? lang : 'lt';
  document.documentElement.lang = selected;
  storage.set(selected);

  translatableNodes.forEach(node => {
    const key = node.dataset.i18n;
    if (translations[selected][key]) node.textContent = translations[selected][key];
  });

  translatableAltNodes.forEach(node => {
    const key = node.dataset.i18nAlt;
    if (translations[selected][key]) node.setAttribute('alt', translations[selected][key]);
  });

  translatableAriaNodes.forEach(node => {
    const key = node.dataset.i18nAria;
    if (translations[selected][key]) node.setAttribute('aria-label', translations[selected][key]);
  });

  figureNodes.forEach(node => {
    const key = node.dataset.figure;
    if (key === 'progress') node.textContent = formatPercent(projectFigures.progress, selected);
    else if (typeof projectFigures[key] === 'number') node.textContent = formatCurrency(projectFigures[key], selected);
  });

  if (progressFill) progressFill.style.width = projectFigures.progress + '%';
  if (contactLink) contactLink.href = selected === 'ru' ? 'https://bukiski-hram.net/ru/contacts.html' : 'https://bukiski-hram.net/lt/contacts.html';

  langButtons.forEach(button => {
    const active = button.dataset.lang === selected;
    button.classList.toggle('is-active', active);
    button.setAttribute('aria-pressed', String(active));
  });

  updateMeta(selected);
}

langButtons.forEach(button => button.addEventListener('click', () => setLanguage(button.dataset.lang)));
if (yearNode) yearNode.textContent = String(new Date().getFullYear());
setLanguage(storage.get() || 'lt');

const revealNodes = document.querySelectorAll('.reveal');
const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
if (!reducedMotion && 'IntersectionObserver' in window) {
  const observer = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });
  revealNodes.forEach(node => observer.observe(node));
} else {
  revealNodes.forEach(node => node.classList.add('is-visible'));
}
